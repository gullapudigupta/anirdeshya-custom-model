/**
 * Pre-Commit Hook Integration
 *
 * Installs and manages Git pre-commit hooks that run quality analysis
 * before allowing a commit. Works with Husky, simple-git-hooks, or
 * direct .git/hooks installation.
 *
 * Inspired by: ESLint/Prettier Git hooks
 *
 * @module integrations/pre-commit-hooks
 */

'use strict';

const fs = require('fs');
const path = require('path');
const { execSync } = require('child_process');

/** Supported hook managers */
const MANAGERS = {
  HUSKY: 'husky',
  SIMPLE_GIT_HOOKS: 'simple-git-hooks',
  LEFTHOOK: 'lefthook',
  DIRECT: 'direct'  // write directly to .git/hooks/pre-commit
};

/** The shell script injected into pre-commit hooks */
const HOOK_SCRIPT = `
#!/usr/bin/env sh
# Advanced Quality Tool — pre-commit hook
# Auto-generated by aqt pre-commit install
# To remove: run "aqt pre-commit uninstall"

AQT_BIN="$(npm bin)/aqt"
if [ ! -f "$AQT_BIN" ]; then
  AQT_BIN="npx aqt"
fi

echo "[AQT] Running pre-commit quality check..."

# Get staged files
STAGED=$(git diff --cached --name-only --diff-filter=ACM | grep -E "\\.(js|ts|jsx|tsx|mjs|cjs|py|go|cs|rb|php|rs)$")

if [ -z "$STAGED" ]; then
  echo "[AQT] No supported files staged — skipping."
  exit 0
fi

# Run analysis on staged files
$AQT_BIN analyze --files "$STAGED" --staged --fail-on-error

AQT_EXIT=$?

if [ $AQT_EXIT -ne 0 ]; then
  echo "[AQT] ❌ Quality check failed. Fix the issues above before committing."
  echo "[AQT]    Use --no-verify to skip (not recommended)."
  exit 1
fi

echo "[AQT] ✅ Quality check passed."
exit 0
`.trimStart();

class PreCommitHooks {
  /**
   * @param {object} [options={}]
   * @param {string} [options.projectRoot=process.cwd()]
   * @param {string} [options.manager='auto'] - Hook manager to use, or 'auto' to detect
   * @param {boolean} [options.verbose=false]
   * @param {boolean} [options.dryRun=false]
   */
  constructor(options = {}) {
    this.options = options;
    this.verbose = options.verbose || false;
    this.dryRun = options.dryRun || false;
    this.projectRoot = options.projectRoot || process.cwd();
    this.manager = options.manager || 'auto';
  }

  // ─── Public API ────────────────────────────────────────────────────────────

  /**
   * Detect which hook manager is installed in the project.
   * @returns {string} Manager name from MANAGERS
   */
  detectManager() {
    const pkg = this._readPackageJson();

    if (pkg) {
      if (pkg.dependencies?.husky || pkg.devDependencies?.husky) return MANAGERS.HUSKY;
      if (pkg.dependencies?.['simple-git-hooks'] || pkg.devDependencies?.['simple-git-hooks']) {
        return MANAGERS.SIMPLE_GIT_HOOKS;
      }
      if (pkg.dependencies?.lefthook || pkg.devDependencies?.lefthook) return MANAGERS.LEFTHOOK;
    }

    return MANAGERS.DIRECT;
  }

  /**
   * Install the pre-commit hook using the detected or configured manager.
   * @returns {{ success: boolean, manager: string, path?: string, message: string }}
   */
  install() {
    const manager = this.manager === 'auto' ? this.detectManager() : this.manager;
    this._log(`Installing pre-commit hook via ${manager}`);

    try {
      switch (manager) {
        case MANAGERS.HUSKY:
          return this._installHusky();
        case MANAGERS.SIMPLE_GIT_HOOKS:
          return this._installSimpleGitHooks();
        case MANAGERS.LEFTHOOK:
          return this._installLefthook();
        case MANAGERS.DIRECT:
        default:
          return this._installDirect();
      }
    } catch (err) {
      return { success: false, manager, message: `Installation failed: ${err.message}` };
    }
  }

  /**
   * Uninstall the AQT pre-commit hook.
   * @returns {{ success: boolean, message: string }}
   */
  uninstall() {
    const manager = this.manager === 'auto' ? this.detectManager() : this.manager;
    this._log(`Uninstalling pre-commit hook (manager: ${manager})`);

    try {
      switch (manager) {
        case MANAGERS.HUSKY:
          return this._uninstallHusky();
        case MANAGERS.DIRECT:
        default:
          return this._uninstallDirect();
      }
    } catch (err) {
      return { success: false, message: `Uninstall failed: ${err.message}` };
    }
  }

  /**
   * Check whether the AQT hook is currently installed.
   * @returns {{ installed: boolean, manager: string, path?: string }}
   */
  isInstalled() {
    const hookPath = this._getDirectHookPath();
    if (fs.existsSync(hookPath)) {
      const content = fs.readFileSync(hookPath, 'utf8');
      if (content.includes('Advanced Quality Tool')) {
        return { installed: true, manager: MANAGERS.DIRECT, path: hookPath };
      }
    }

    const huskyHook = path.join(this.projectRoot, '.husky', 'pre-commit');
    if (fs.existsSync(huskyHook)) {
      const content = fs.readFileSync(huskyHook, 'utf8');
      if (content.includes('aqt')) {
        return { installed: true, manager: MANAGERS.HUSKY, path: huskyHook };
      }
    }

    return { installed: false, manager: 'none' };
  }

  /**
   * Generate the hook script (for inspection without installing).
   * @returns {string}
   */
  generateScript() {
    return HOOK_SCRIPT;
  }

  // ─── Installers ─────────────────────────────────────────────────────────────

  _installHusky() {
    const huskyDir = path.join(this.projectRoot, '.husky');

    if (!fs.existsSync(huskyDir)) {
      if (this.dryRun) {
        this._log('[DRY RUN] Would run: npx husky install');
      } else {
        execSync('npx husky install', { cwd: this.projectRoot, stdio: 'pipe' });
      }
    }

    const hookFile = path.join(huskyDir, 'pre-commit');
    const hookContent = `#!/usr/bin/env sh\n. "$(dirname "$0")/_/husky.sh"\n\nnpx aqt analyze --staged --fail-on-error\n`;

    if (!this.dryRun) {
      if (!fs.existsSync(huskyDir)) fs.mkdirSync(huskyDir, { recursive: true });
      fs.writeFileSync(hookFile, hookContent, { mode: 0o755 });
    }

    this._log(`[DRY RUN: ${this.dryRun}] Husky pre-commit hook → ${hookFile}`);
    return {
      success: true,
      manager: MANAGERS.HUSKY,
      path: hookFile,
      message: `Husky pre-commit hook installed at ${hookFile}`
    };
  }

  _installSimpleGitHooks() {
    const pkg = this._readPackageJson();
    const pkgPath = path.join(this.projectRoot, 'package.json');

    if (pkg && pkgPath) {
      if (!pkg['simple-git-hooks']) pkg['simple-git-hooks'] = {};
      pkg['simple-git-hooks']['pre-commit'] = 'npx aqt analyze --staged --fail-on-error';

      if (!this.dryRun) {
        fs.writeFileSync(pkgPath, JSON.stringify(pkg, null, 2) + '\n');
        execSync('npx simple-git-hooks', { cwd: this.projectRoot, stdio: 'pipe' });
      }
    }

    return {
      success: true,
      manager: MANAGERS.SIMPLE_GIT_HOOKS,
      message: 'simple-git-hooks pre-commit entry added to package.json'
    };
  }

  _installLefthook() {
    const lefthookPath = path.join(this.projectRoot, 'lefthook.yml');
    const entry = `
pre-commit:
  commands:
    aqt-quality-check:
      run: npx aqt analyze --staged --fail-on-error
      glob: "*.{js,ts,jsx,tsx,py,go,cs,rb,php,rs}"
`.trimStart();

    if (!this.dryRun) {
      const existing = fs.existsSync(lefthookPath) ? fs.readFileSync(lefthookPath, 'utf8') : '';
      if (!existing.includes('aqt-quality-check')) {
        fs.appendFileSync(lefthookPath, '\n' + entry);
      }
      execSync('npx lefthook install', { cwd: this.projectRoot, stdio: 'pipe' });
    }

    return {
      success: true,
      manager: MANAGERS.LEFTHOOK,
      path: lefthookPath,
      message: `Lefthook pre-commit hook added to ${lefthookPath}`
    };
  }

  _installDirect() {
    const hookPath = this._getDirectHookPath();
    const hookDir = path.dirname(hookPath);

    if (!fs.existsSync(hookDir)) {
      return { success: false, manager: MANAGERS.DIRECT, message: `Not a git repository: ${this.projectRoot}` };
    }

    let finalScript = HOOK_SCRIPT;

    // Preserve existing hook content if not already AQT
    if (fs.existsSync(hookPath)) {
      const existing = fs.readFileSync(hookPath, 'utf8');
      if (existing.includes('Advanced Quality Tool')) {
        return { success: true, manager: MANAGERS.DIRECT, path: hookPath, message: 'Hook already installed.' };
      }
      // Append AQT check to existing hook
      finalScript = existing.trimEnd() + '\n\n# --- Advanced Quality Tool ---\n' +
                    HOOK_SCRIPT.split('\n').slice(3).join('\n');
    }

    if (!this.dryRun) {
      fs.writeFileSync(hookPath, finalScript, { mode: 0o755 });
    }

    this._log(`Hook written to ${hookPath}`);
    return {
      success: true,
      manager: MANAGERS.DIRECT,
      path: hookPath,
      message: `Pre-commit hook installed at ${hookPath}`
    };
  }

  _uninstallHusky() {
    const hookFile = path.join(this.projectRoot, '.husky', 'pre-commit');
    if (fs.existsSync(hookFile)) {
      if (!this.dryRun) fs.unlinkSync(hookFile);
      return { success: true, message: `Removed ${hookFile}` };
    }
    return { success: true, message: 'No Husky pre-commit hook found.' };
  }

  _uninstallDirect() {
    const hookPath = this._getDirectHookPath();
    if (!fs.existsSync(hookPath)) {
      return { success: true, message: 'No pre-commit hook found.' };
    }
    const content = fs.readFileSync(hookPath, 'utf8');
    if (!content.includes('Advanced Quality Tool')) {
      return { success: true, message: 'Hook does not contain AQT script; skipping.' };
    }
    if (!this.dryRun) fs.unlinkSync(hookPath);
    return { success: true, message: `Removed pre-commit hook at ${hookPath}` };
  }

  // ─── Helpers ───────────────────────────────────────────────────────────────

  _getDirectHookPath() {
    return path.join(this.projectRoot, '.git', 'hooks', 'pre-commit');
  }

  _readPackageJson() {
    const pkgPath = path.join(this.projectRoot, 'package.json');
    if (!fs.existsSync(pkgPath)) return null;
    try { return JSON.parse(fs.readFileSync(pkgPath, 'utf8')); } catch { return null; }
  }

  _log(msg) { if (this.verbose) console.log(`[PreCommitHooks] ${msg}`); }
}

module.exports = { PreCommitHooks, MANAGERS, HOOK_SCRIPT };
